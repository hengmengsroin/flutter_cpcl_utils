/// Backward-compatible alias for [CpclGenerator].
typedef Generator = CpclGenerator;

/// Builder for CPCL command streams.
class CpclGenerator {
  /// Creates a CPCL generator.
  CpclGenerator({
    this.newLine = '\r\n',
    this.codec = latin1,
    this.config,
    List<CpclCommand> commands = const [],
  }) : _commands = CpclCommandBuffer(codec: codec, newLine: newLine),
       _declarativeCommands = List.unmodifiable(commands);

  /// Newline sequence used between command lines.
  final String newLine;

  /// Encoding used for textual CPCL commands.
  final Encoding codec;

  /// Optional declarative configuration used during build.
  final CpclConfiguration? config;
  final CpclCommandBuffer _commands;
  final List<CpclCommand> _declarativeCommands;
  bool _hasAppliedDeclarativeCommands = false;

  /// Declarative commands attached to this generator.
  List<CpclCommand> get commands => _declarativeCommands;

  /// Clears generated bytes and resets declarative execution state.
  CpclGenerator reset() {
    _commands.clear();
    _hasAppliedDeclarativeCommands = false;
    return this;
  }

  /// Builds CPCL bytes synchronously.
  Uint8List build() {
    _applyDeclarativeCommandsSync();
    return _commands.build();
  }

  /// Builds CPCL bytes asynchronously.
  Future<Uint8List> buildAsync() async {
    await _applyDeclarativeCommandsAsync();
    return _commands.build();
  }

  /// Returns generated bytes as a `List<int>`.
  List<int> bytes() => build();

  /// Returns a text preview of synchronously built CPCL output.
  String preview() => String.fromCharCodes(build());

  /// Returns a text preview of asynchronously built CPCL output.
  Future<String> previewAsync() async =>
      String.fromCharCodes(await buildAsync());

  /// Appends bytes directly to the command stream.
  CpclGenerator rawBytes(List<int> bytes) {
    _commands.addRawBytes(bytes);
    return this;
  }

  /// Appends a raw CPCL command line.
  CpclGenerator rawCommand(String command) {
    _commands.addCommand(command);
    return this;
  }

  /// Writes the label initialization header and page width.
  ///
  /// [horizontalDpi] and [verticalDpi] default to 203, the 8 dot/mm resolution
  /// used by [CpclPrintDensity.d8] and by [CpclConfiguration].
  CpclGenerator initialize(
    CpclLabelSize size, {
    int copies = 1,
    int offset = 0,
    int horizontalDpi = 203,
    int verticalDpi = 203,
  }) {
    requirePositive(size.width, 'size.width');
    requirePositive(size.height, 'size.height');
    requirePositive(copies, 'copies');
    requireNonNegative(offset, 'offset');
    requirePositive(horizontalDpi, 'horizontalDpi');
    requirePositive(verticalDpi, 'verticalDpi');

    return this
      ..rawCommand(
        '! $offset $horizontalDpi $verticalDpi ${size.height} $copies',
      )
      ..pageWidth(size.width);
  }

  /// Sets label page width in dots.
  CpclGenerator pageWidth(int width) {
    requirePositive(width, 'width');
    return rawCommand('PAGE-WIDTH $width');
  }

  /// Sets print speed (`0..5`).
  CpclGenerator speed(int value) {
    requireRange(value, 0, 5, 'value');
    return rawCommand('SPEED $value');
  }

  /// Sets print tone (`0..3`).
  CpclGenerator tone(int value) {
    requireRange(value, 0, 3, 'value');
    return rawCommand('TONE $value');
  }

  /// Sets print contrast (`0..3`).
  CpclGenerator contrast(int value) {
    requireRange(value, 0, 3, 'value');
    return rawCommand('CONTRAST $value');
  }

  /// Sets country code for character handling.
  CpclGenerator country(CpclCountryCode value) {
    return rawCommand('COUNTRY ${value.value}');
  }

  /// Adds prefeed distance in dots.
  CpclGenerator prefeed(int dots) {
    requireNonNegative(dots, 'dots');
    return rawCommand('PREFEED $dots');
  }

  /// Adds postfeed distance in dots.
  CpclGenerator postfeed(int dots) {
    requireNonNegative(dots, 'dots');
    return rawCommand('POSTFEED $dots');
  }

  /// Sets alignment mode to center.
  CpclGenerator center() => rawCommand('CENTER');

  /// Sets alignment mode to left.
  CpclGenerator left() => rawCommand('LEFT');

  /// Sets alignment mode to right.
  CpclGenerator right() => rawCommand('RIGHT');

  /// Configures line-print mode using `SETLP`.
  ///
  /// Deprecated: In Zebra CPCL, `SETLP` is a utility-session command and should not
  /// be placed bare inside a page-mode label session (`! 0 ...`).
  ///
  /// This method now emits the full utility-session command `! U1 SETLP ...` to prevent
  /// generating malformed CPCL. Prefer [setLinePrint] in new code.
  @Deprecated(
    'Use setLinePrint() to explicitly emit utility-session "! U1 SETLP".',
  )
  CpclGenerator setLp(CpclLinePrintOptions options) => setLinePrint(options);

  /// Sets line-print font configuration using the `! U1` utility command prefix.
  ///
  /// This is the documented CPCL syntax for utility-session line-print setup
  /// (e.g. `! U1 SETLP 7 0 24`).
  CpclGenerator setLinePrint(CpclLinePrintOptions options) {
    requireNonNegative(options.size, 'options.size');
    requirePositive(options.lineSpacing, 'options.lineSpacing');
    return rawCommand('! U1 SETLP ${options.formatArguments()}');
  }

  /// Sets persistent font magnification using `SETMAG`.
  ///
  /// [width] and [height] are direct scale factors (`1..16`). Use `0, 0` to
  /// reset magnification to standard resident font dimensions.
  ///
  /// Note: In CPCL, `SETMAG` modifies printer state persistently across labels
  /// until explicitly reset with `setMag(0, 0)`.
  CpclGenerator setMag(int width, int height) {
    if (width == 0 && height == 0) {
      return rawCommand('SETMAG 0 0');
    }
    requireRange(width, 1, 16, 'width');
    requireRange(height, 1, 16, 'height');
    return rawCommand('SETMAG $width $height');
  }

  /// Adds a `TEXT` command at `[x, y]`.
  CpclGenerator text(
    int x,
    int y,
    String value, {
    CpclTextStyle style = const CpclTextStyle(),
  }) {
    _validateTextStyle(style);
    final sanitized = sanitizeCpclText(value);
    final hasMagnification = style.xMultiplier > 1 || style.yMultiplier > 1;

    if (hasMagnification) {
      rawCommand('SETMAG ${style.xMultiplier} ${style.yMultiplier}');
    }

    rawCommand(
      '${style.rotation.textCommand} ${style.font.value} ${style.size} $x $y $sanitized',
    );

    if (hasMagnification) {
      rawCommand('SETMAG 0 0');
    }

    return this;
  }

  /// Adds a `LINE` command.
  CpclGenerator line(int x0, int y0, int x1, int y1, {int thickness = 1}) {
    requirePositive(thickness, 'thickness');
    return rawCommand('LINE $x0 $y0 $x1 $y1 $thickness');
  }

  /// Adds a `BOX` command.
  CpclGenerator box(int x0, int y0, int x1, int y1, {int thickness = 1}) {
    requirePositive(thickness, 'thickness');
    return rawCommand('BOX $x0 $y0 $x1 $y1 $thickness');
  }

  /// Adds an `INVERSE-LINE` command covering a rectangle at `[x, y]`.
  ///
  /// Zebra CPCL uses the same geometry as [line]:
  /// `INVERSE-LINE {x0} {y0} {x1} {y1} {thickness}`.
  /// A rectangle [width] dots wide and [height] dots tall is written as the
  /// horizontal bar `INVERSE-LINE x y (x+width) y height`.
  ///
  /// The printer inverts objects drawn earlier that fall inside the rectangle.
  /// Objects drawn after this command are not inverted.
  CpclGenerator inverseLine(int x, int y, int width, int height) {
    requireRange(x, 0, 65535, 'x');
    requireRange(y, 0, 65535, 'y');
    requireRange(width, 1, 65535, 'width');
    requireRange(height, 1, 65535, 'height');
    final endX = x + width;
    requireRange(endX, 0, 65535, 'x + width');
    return rawCommand('INVERSE-LINE $x $y $endX $y $height');
  }

  void _validateBarcodeParameters(
    int x,
    int y,
    CpclBarcodeOptions options,
    String content,
  ) {
    requireRange(x, 0, 65535, 'x');
    requireRange(y, 0, 65535, 'y');
    requireRange(options.width, 0, 65535, 'options.width');
    CpclBarcodeRatio.validateCode(options.ratio);
    requireRange(options.height, 0, 65535, 'options.height');
    final sanitized = sanitizeCpclText(content);
    final encoded = codec.encode(sanitized);
    if (encoded.length > 8191) {
      throw ArgumentError.value(
        content.length,
        'content',
        'Barcode data payload exceeds CPCL maximum limit of 8191 bytes (${encoded.length} bytes).',
      );
    }
  }

  /// Adds a `BARCODE` command.
  CpclGenerator barcode(
    int x,
    int y,
    String content, {
    CpclBarcodeOptions options = const CpclBarcodeOptions(),
  }) {
    _validateBarcodeParameters(x, y, options, content);
    return rawCommand(
      'BARCODE ${options.type.value} ${options.width} ${options.ratio} ${options.height} $x $y ${sanitizeCpclText(content)}',
    );
  }

  /// Adds a `VBARCODE` command.
  CpclGenerator verticalBarcode(
    int x,
    int y,
    String content, {
    CpclBarcodeOptions options = const CpclBarcodeOptions(),
  }) {
    _validateBarcodeParameters(x, y, options, content);
    return rawCommand(
      'VBARCODE ${options.type.value} ${options.width} ${options.ratio} ${options.height} $x $y ${sanitizeCpclText(content)}',
    );
  }

  /// Adds a CPCL QR code command sequence.
  CpclGenerator qrCode(
    int x,
    int y,
    String content, {
    CpclQrCodeOptions options = const CpclQrCodeOptions(),
  }) {
    requireRange(options.model, 1, 2, 'options.model');
    requireRange(options.unit, 1, 32, 'options.unit');

    return this
      ..rawCommand('B QR $x $y M ${options.model} U ${options.unit}')
      ..rawCommand('${options.ecc.value}A,${sanitizeCpclText(content)}')
      ..rawCommand('ENDQR');
  }

  /// Adds a `CG` (COMPRESSED-GRAPHICS) bitmap command from an [image].
  ///
  /// In Zebra CPCL documentation, this command is named `COMPRESSED-GRAPHICS`,
  /// but the payload is not algorithmically compressed (no RLE, LZW, or Deflate
  /// compression is applied by this library). Instead, it sends raw 1-bit binary
  /// bytes (1 byte per 8 horizontal dots, MSB first), which is twice as compact
  /// as `EG` hexadecimal ASCII character representation.
  CpclGenerator bitmap(int x, int y, img.Image image, {int threshold = 127}) {
    requireRange(threshold, 0, 255, 'threshold');
    final raster = _rasterize(image, threshold: threshold);
    _commands.addEncodedText('CG ${raster.widthBytes} ${raster.height} $x $y ');
    _commands.addRawBytes(raster.bytes);
    _commands.addEncodedText(newLine);
    return this;
  }

  /// Adds a `CG` (COMPRESSED-GRAPHICS) command using raw 8-bit binary bitmap data.
  ///
  /// Named to align with the official Zebra CPCL `COMPRESSED-GRAPHICS` command name.
  /// Note: The payload is raw 1-bit binary bitmap data (1 byte per 8 pixels);
  /// no algorithmic compression (e.g. RLE, LZW, or Deflate) is applied by this library.
  CpclGenerator compressedGraphics(
    int x,
    int y,
    img.Image image, {
    int threshold = 127,
  }) => bitmap(x, y, image, threshold: threshold);

  /// Adds an `EG` (EXPANDED-GRAPHICS) command using ASCII hexadecimal encoding.
  ///
  /// In CPCL, `EG` encodes each byte of 1-bit bitmap data as two uppercase
  /// hexadecimal ASCII characters (`00`..`FF`).
  CpclGenerator expandedGraphics(
    int x,
    int y,
    img.Image image, {
    int threshold = 127,
  }) {
    requireRange(threshold, 0, 255, 'threshold');
    final raster = _rasterize(image, threshold: threshold);
    final hexBuffer = StringBuffer();
    for (final byte in raster.bytes) {
      hexBuffer.write(byte.toRadixString(16).padLeft(2, '0').toUpperCase());
    }
    rawCommand('EG ${raster.widthBytes} ${raster.height} $x $y $hexBuffer');
    return this;
  }

  /// Renders Flutter text and inserts it as a bitmap.
  ///
  /// This can be used for any script or custom font supported by Flutter,
  /// including Khmer, Thai, Arabic, CJK, and custom icon fonts.
  Future<CpclGenerator> renderedText(
    int x,
    int y,
    String value, {
    required CpclRenderedTextOptions options,
  }) async {
    final rendered = await _renderFlutterText(value, options: options);
    return bitmap(x, y, rendered, threshold: options.threshold);
  }

  /// Backward-compatible alias for [renderedText].
  ///
  /// Renders Flutter text and inserts it as a bitmap. Prefer [renderedText]
  /// for new code.
  Future<CpclGenerator> khmerText(
    int x,
    int y,
    String value, {
    required CpclRenderedTextOptions options,
  }) => renderedText(x, y, value, options: options);

  /// Appends `FORM`.
  CpclGenerator form() => rawCommand('FORM');

  /// Appends `PRINT`.
  CpclGenerator print() => rawCommand('PRINT');

  void _applyDeclarativeCommandsSync() {
    if (_hasAppliedDeclarativeCommands) {
      return;
    }

    final asyncCommands = _declarativeCommands
        .where((command) => command.requiresAsync)
        .toList(growable: false);

    if (asyncCommands.isNotEmpty) {
      throw StateError(
        'This label includes async commands. Use buildAsync() or previewAsync() instead.',
      );
    }

    _applyConfiguration();
    for (final command in _declarativeCommands) {
      command.apply(this);
    }
    _finalizeDeclarativeConfiguration();
    _hasAppliedDeclarativeCommands = true;
  }

  Future<void> _applyDeclarativeCommandsAsync() async {
    if (_hasAppliedDeclarativeCommands) {
      return;
    }

    _applyConfiguration();
    for (final command in _declarativeCommands) {
      await command.applyAsync(this);
    }
    _finalizeDeclarativeConfiguration();
    _hasAppliedDeclarativeCommands = true;
  }

  void _applyConfiguration() {
    final currentConfig = config;
    if (currentConfig == null) {
      return;
    }

    // In Zebra CPCL, SETLP is a utility-session command. If linePrintOptions is
    // specified, emit the one-line utility command (! U1 SETLP ...) before beginning
    // the page-mode label session (! 0 ...) to avoid placing utility commands inside
    // a page-mode label.
    final linePrintOptions = currentConfig.linePrintOptions;
    if (linePrintOptions != null) {
      setLinePrint(linePrintOptions);
    }

    initialize(
      CpclLabelSize(currentConfig.printWidth, currentConfig.labelLength),
      copies: currentConfig.copies,
      offset: currentConfig.offset,
      horizontalDpi: currentConfig.resolvedHorizontalDpi,
      verticalDpi: currentConfig.resolvedVerticalDpi,
    );

    final speedValue = currentConfig.speed;
    if (speedValue != null) {
      speed(speedValue);
    }

    final toneValue = currentConfig.tone;
    if (toneValue != null) {
      tone(toneValue);
    }

    final contrastValue = currentConfig.contrast;
    if (contrastValue != null) {
      contrast(contrastValue);
    }

    final countryValue = currentConfig.country;
    if (countryValue != null) {
      country(countryValue);
    }

    final alignmentValue = currentConfig.alignment;
    switch (alignmentValue) {
      case CpclAlignment.left:
        left();
        break;
      case CpclAlignment.center:
        center();
        break;
      case CpclAlignment.right:
        right();
        break;
      case null:
        break;
    }

    final prefeedValue = currentConfig.prefeed;
    if (prefeedValue != null) {
      prefeed(prefeedValue);
    }

    final postfeedValue = currentConfig.postfeed;
    if (postfeedValue != null) {
      postfeed(postfeedValue);
    }
  }

  void _finalizeDeclarativeConfiguration() {
    final currentConfig = config;
    if (currentConfig == null) {
      return;
    }

    if (currentConfig.autoForm) {
      form();
    }

    if (currentConfig.autoPrint) {
      print();
    }
  }

  void _validateTextStyle(CpclTextStyle style) {
    requireNonNegative(style.size, 'style.size');
    requireRange(style.xMultiplier, 1, 16, 'style.xMultiplier');
    requireRange(style.yMultiplier, 1, 16, 'style.yMultiplier');
  }

  Future<img.Image> _renderFlutterText(
    String value, {
    required CpclRenderedTextOptions options,
  }) async {
    if (value.isEmpty) {
      throw ArgumentError.value(value, 'value', 'Must not be empty');
    }

    requirePositive(options.pixelRatio, 'options.pixelRatio');
    requireNonNegative(options.padding, 'options.padding');
    requireRange(options.threshold, 0, 255, 'options.threshold');

    final textPainter = TextPainter(
      text: TextSpan(text: value, style: options.style),
      textAlign: options.textAlign,
      textDirection: options.textDirection,
    );

    textPainter.layout(maxWidth: options.maxWidth ?? double.infinity);

    final contentWidth = textPainter.width.ceil();
    final contentHeight = textPainter.height.ceil();
    final padding = options.padding.ceil();
    final imageWidth = (contentWidth + padding * 2).clamp(1, 65535);
    final imageHeight = (contentHeight + padding * 2).clamp(1, 65535);
    final outputWidth = (imageWidth * options.pixelRatio).ceil();
    final outputHeight = (imageHeight * options.pixelRatio).ceil();
    if (outputWidth > 65535 || outputHeight > 65535) {
      throw ArgumentError(
        'Rendered text is ${outputWidth}x$outputHeight pixels, which exceeds the CPCL limit of 65535.',
      );
    }

    final recorder = ui.PictureRecorder();
    final canvas = Canvas(recorder);
    // Picture.toImage does not scale. Scale the canvas so pixelRatio becomes
    // printer dots instead of empty margin around 1x glyphs.
    canvas.scale(options.pixelRatio, options.pixelRatio);
    final backgroundPaint = Paint()..color = options.backgroundColor;
    canvas.drawRect(
      Rect.fromLTWH(0, 0, imageWidth.toDouble(), imageHeight.toDouble()),
      backgroundPaint,
    );
    textPainter.paint(canvas, Offset(options.padding, options.padding));

    final picture = recorder.endRecording();
    final rendered = await picture.toImage(outputWidth, outputHeight);
    final byteData = await rendered.toByteData(
      format: ui.ImageByteFormat.rawRgba,
    );
    rendered.dispose();
    if (byteData == null) {
      throw StateError('Failed to convert rendered text to bytes.');
    }

    final bytes = byteData.buffer.asUint8List();
    return img.Image.fromBytes(
      width: rendered.width,
      height: rendered.height,
      bytes: bytes.buffer,
      numChannels: 4,
      order: img.ChannelOrder.rgba,
    );
  }

  _RasterizedBitmap _rasterize(img.Image source, {required int threshold}) {
    final grayscaleImage = img.grayscale(img.Image.from(source));
    final widthBytes = (grayscaleImage.width + 7) ~/ 8;
    final paddedWidth = widthBytes * 8;
    final bytes = Uint8List(widthBytes * grayscaleImage.height);

    for (var y = 0; y < grayscaleImage.height; y++) {
      for (var x = 0; x < paddedWidth; x++) {
        final isBlack =
            x < grayscaleImage.width &&
            _isPrintedDot(grayscaleImage.getPixel(x, y), threshold);
        if (isBlack) {
          final byteIndex = y * widthBytes + (x ~/ 8);
          final bitIndex = 7 - (x % 8);
          bytes[byteIndex] |= 1 << bitIndex;
        }
      }
    }

    return _RasterizedBitmap(
      widthBytes: widthBytes,
      height: grayscaleImage.height,
      bytes: bytes,
    );
  }
}

/// CPCL prints on white stock. Composite [pixel] onto white, then treat it as
/// a printed dot when the result is at or below [threshold].
///
/// Alpha is part of that composite. A fully transparent pixel is unprinted
/// white, including when its RGB channels are black.
bool _isPrintedDot(img.Pixel pixel, int threshold) {
  final alpha = pixel.aNormalized.toDouble().clamp(0.0, 1.0);
  final composited = pixel.r * alpha + 255 * (1 - alpha);
  return composited <= threshold;
}

class _RasterizedBitmap {
  const _RasterizedBitmap({
    required this.widthBytes,
    required this.height,
    required this.bytes,
  });

  final int widthBytes;
  final int height;
  final Uint8List bytes;
}
